//! Texts the coder writes to GitHub: PR body (summary, stats, footer), prompt appendices.

use regex::Regex;
use std::sync::OnceLock;

pub const FOOTER: &str = "\n\n---\n🤖 *Generated by the Lunima team agent (Claude Code).*\n\n<details><summary><b>How to steer this agent</b> (labels &amp; comments)</summary>\n\n**On an issue:**\n- `agent-task` — the agent picks it up and implements it\n- `complex` — bigger budget + a UX design pass + a step-by-step screenshot walkthrough, and runs the coder on the premium Claude model\n- **Cost tier** (coder model): `eco` = cheapest (only in third-party-cleared, non-forced repos; ignored elsewhere) · *(no tier label)* = repo default · `claudeapi` = force premium Claude (wins everywhere)\n- `Team branch: team/x` — branch off `team/x` and target the PR at it (auto-created if missing)\n\n**On this PR:**\n- Comment `@agent <request>` — the agent implements your feedback on this branch and replies with a report + updated screenshots\n</details>";

/// Appended to every coder prompt; the block becomes the PR description.
pub const PR_SUMMARY_INSTRUCTION: &str = "\n\n## 📝 PR Report Format — STRICT\nEnd your final message with EXACTLY this block (it becomes the PR\ndescription — the human reviews PRs quickly, so keep it DENSE):\n\n=== PR SUMMARY ===\n- <what changed, one bullet per change — short sentences, no filler>\n- <key decisions incl. UX decisions + rejected alternatives, if any>\n- <how it was verified: build/tests/screenshots>\n=== END ===\n\nRules: 4-8 bullets total, max ~15 words each, no headings inside the\nblock, no code dumps, no restating the issue text.\n";

fn summary_re() -> &'static Regex {
    static R: OnceLock<Regex> = OnceLock::new();
    R.get_or_init(|| Regex::new(r"(?s)===\s*PR SUMMARY\s*===\s*(.*?)\s*===\s*END\s*===").expect("regex"))
}

/// The PR SUMMARY block, else the end of the final message (≤1200 chars).
pub fn pr_summary(output: &str) -> String {
    if let Some(c) = summary_re().captures(output) {
        let s = c[1].trim();
        if !s.is_empty() {
            return s.to_string();
        }
    }
    crate::shell::tail(output.trim(), 1200)
}

/// Read-only access to sibling repos of the org (via the gh login, no token in the prompt).
pub fn org_note(org: &str) -> String {
    if org.is_empty() {
        return String::new();
    }
    format!("\n\n## 🔎 Cross-repo reference access (read-only)\nYou have READ access to every repository in the `{org}` GitHub\norg. When this task depends on a sibling repo — an ISA definition (e.g.\nraycore-isa is the source of truth for assembly), a compiler, a shared SDK —\nconsult the actual source instead of guessing:\n```bash\ngh repo clone {org}/<repo> <temp-dir>/ref-<repo> -- --depth 1\n```\nRules: reference clones are read-only — never commit or push to them, and\nnever copy secrets or wholesale code from them into this repo.\n")
}

/// UX design pass for COMPLEX issues (incl. the screenshot walkthrough request).
pub fn ux_note(issue: u64) -> String {
    format!("\n\n## 🎨 UX Design Pass\nDon't stop at the core business logic — design the *interaction* a real user needs.\n1. **Personas:** Look for a \"Personas\" section in CLAUDE.md. If present, design explicitly from those personas' perspective — and if that section references another file (e.g. personas.md), read it first. If absent, reason briefly about the likely primary user — but don't fabricate elaborate personas.\n2. **Ask the design question, not just the code question:** decide the *right* interaction — is a plain button enough, or does the user need a dialog/wizard to understand it, inline validation, sensible defaults — or should the action just happen automatically (with feedback) so there's nothing to click at all? Consider discoverability, feedback, and error states.\n3. **Reuse existing patterns:** match the app's existing dialogs, styles, and MVVM conventions — don't invent inconsistent new UI.\n4. **You have full autonomy** to add whatever UI/flows/affordances make the feature genuinely understandable — implement them as part of this ticket (still a complete vertical slice with tests). Note the key UX decisions (and rejected alternatives) as bullets in your PR SUMMARY block.\n5. **Visual walkthrough (for the PR):** If this change adds or alters UI, capture the user flow so a reviewer sees it without checking out. Using the headless screenshot harness (see `UnitTests/UI/UiScreenshotTests.cs` for the Avalonia + Skia pattern), render the relevant view(s) in **each meaningful state** and save PNGs to `artifacts/ui-screenshots/issue-{issue}/` named in step order (e.g. `01-initial.png`, `02-after-click.png`, `03-result.png`), plus a `manifest.json` — a JSON array of `{{\"file\": \"01-initial.png\", \"caption\": \"...\"}}` in order. Captions: ONE short sentence — what the user sees/does in that step. The agent embeds these into the PR automatically — you do NOT need to touch the PR body.\n")
}

/// Session statistics for the PR body.
pub struct Stats {
    pub sessions: u32,
    pub turns: u32,
    pub tokens: u64,
    pub cost: f64,
    /// (tool, count) of python-dev-tools usage
    pub tools: Vec<(String, usize)>,
}

pub fn stats_block(s: &Stats) -> String {
    let mut out = format!(
        "\n## [AGENT] Agent Stats\n\n- **Sessions:** {}\n- **Total turns:** {}\n- **Total tokens:** {}\n- **Estimated cost:** ${:.4} USD\n",
        s.sessions,
        s.turns,
        thousands(s.tokens),
        s.cost
    );
    if s.tools.is_empty() {
        out.push_str("\n**Custom Tools Used:** None\n");
    } else {
        out.push_str("\n**Custom Tools Used:**\n");
        for (tool, n) in &s.tools {
            out.push_str(&format!("- `{tool}`: {n} runs\n"));
        }
    }
    out
}

/// python-dev-tools calls among the session's shell commands (both path separators).
pub fn tool_usage(commands: &[String]) -> Vec<(String, usize)> {
    ["semantic_search.py", "smart_test.py"]
        .iter()
        .map(|t| (t.to_string(), commands.iter().filter(|c| c.contains(t) && (c.contains("cap-tools") || c.contains("tools/") || c.contains("tools\\"))).count()))
        .filter(|(_, n)| *n > 0)
        .collect()
}

/// `Automated implementation for #N` must stay the first `#number` (QA fix and PR feedback
/// find the issue by it).
pub fn pr_body(issue: u64, summary: &str, stats: &str, walkthrough: &str) -> String {
    let mut b = format!("Automated implementation for #{issue}\n");
    for part in [summary, stats, walkthrough] {
        if !part.trim().is_empty() {
            b.push('\n');
            b.push_str(part);
            b.push('\n');
        }
    }
    b.push_str(FOOTER);
    b
}

/// `20000000` → `20,000,000`
pub fn thousands(n: u64) -> String {
    let s = n.to_string();
    let mut out = String::new();
    for (i, c) in s.chars().enumerate() {
        if i > 0 && (s.len() - i) % 3 == 0 {
            out.push(',');
        }
        out.push(c);
    }
    out
}

/// First `#123` in a PR body (the linked issue).
pub fn linked_issue(body: &str) -> Option<u64> {
    static R: OnceLock<Regex> = OnceLock::new();
    R.get_or_init(|| Regex::new(r"#(\d+)").expect("regex")).captures(body).and_then(|c| c[1].parse().ok())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn summary_block_or_bounded_tail() {
        assert_eq!(pr_summary("x\n=== PR SUMMARY ===\n- a\n- b\n=== END ===\n"), "- a\n- b");
        let long = "y".repeat(2000);
        let s = pr_summary(&long);
        assert!(s.starts_with("...\n") && s.len() <= 1205);
        assert_eq!(pr_summary(""), "");
    }

    #[test]
    fn body_starts_with_issue_reference_and_ends_with_footer() {
        let b = pr_body(7, "- did it", "", "");
        assert!(b.starts_with("Automated implementation for #7\n"));
        assert!(b.contains("- did it"));
        assert!(b.ends_with("</details>"));
        assert_eq!(linked_issue(&b), Some(7));
    }

    #[test]
    fn numbers_and_tools() {
        assert_eq!(thousands(20_000_000), "20,000,000");
        assert_eq!(thousands(999), "999");
        let cmds = vec!["~/.cap-tools/venv/bin/python3 ~/.cap-tools/smart_test.py".to_string(), "C:\\x\\tools\\semantic_search.py q".into(), "ls".into()];
        let u = tool_usage(&cmds);
        assert_eq!(u, vec![("semantic_search.py".to_string(), 1), ("smart_test.py".to_string(), 1)]);
        assert!(stats_block(&Stats { sessions: 1, turns: 3, tokens: 1234, cost: 0.5, tools: vec![] }).contains("1,234"));
    }

    #[test]
    fn notes() {
        assert!(org_note("").is_empty());
        assert!(org_note("Akhetonics").contains("gh repo clone Akhetonics/<repo>"));
        assert!(ux_note(5).contains("artifacts/ui-screenshots/issue-5/"));
        assert!(ux_note(5).contains("{\"file\""));
    }
}
